"""Inline brand/posters/manifest.json into index.html (between the posters:begin / posters:end markers).

The inlined script runs in <head>, before anything is drawn (not signed in only):
  - picks the poster for this screen's shape (same rule as terrain.js pickPoster),
  - sets --si-lqip (the tiny blurred placeholder, painted with the very first frame),
  - sets --si-poster + its place (same rule as terrain.js posterBox, on the horizon of terrain.js compose), so the SHARP
    poster is painted as soon as it arrives — it does not wait for the scripts (2026-11-18: it used to, and the blurred
    placeholder stayed on screen until every script had loaded),
  - starts downloading the poster at high priority, in parallel with the stylesheets.
The placement is a copy (nothing else has loaded yet); tests/poster-place.html proves it equal to terrain.js.
Run after _guide/make-posters.html:  python -I tools/inline_posters.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
man = json.load(open(os.path.join(ROOT, 'brand', 'posters', 'manifest.json'), encoding='utf-8'))
html_path = os.path.join(ROOT, 'index.html')
html = open(html_path, encoding='utf-8').read()

block = f"""<!-- posters:begin (generated by tools/inline_posters.py from brand/posters/manifest.json — do not edit) -->
  <script>
  window.SAKER_POSTERS = {json.dumps(man, separators=(',', ':'))};
  window.SAKER_POSTER_BOOT = function (W, H) {{   // → the poster for a W×H screen and its place (W, H in CSS px)
    // same rule as terrain.js pickPoster: the widest poster not wider than the screen
    var a = W / H, P = window.SAKER_POSTERS, best = null, fam = [];
    for (var i = 0; i < P.list.length; i++) if ((P.list[i].a < 0.8) === (a < 0.8)) fam.push(P.list[i]);
    fam.sort(function (x, y) {{ return x.a - y.a; }}); best = fam[0] || null;
    for (var j = 0; j < fam.length; j++) if (fam[j].a <= a * 1.002) best = fam[j];
    if (!best) return null;
    // the horizon: same rule as terrain.js compose
    var cy;
    if (a >= 0.8) cy = 0.64 * H;
    else {{
      var t = Math.min(1, Math.max(0, (W - 430) / 170)), sm = t * t * (3 - 2 * t);
      var logoW = W * (0.62 + (0.3255 - 0.62) * sm), logoH = logoW * 307 / 496, k = logoW / 241.8, logoTop = 0.15 * H;
      cy = logoTop + logoH + 52 * k + 120 * k + 0.07 * H;
    }}
    // the place: same rule as terrain.js posterBox
    var h = W / best.a, top = cy - best.h * h;
    if (top > 0 || top + h < H) h = Math.max(cy / best.h, (H - cy) / (1 - best.h), h);
    var w = h * best.a; top = cy - best.h * h;
    // the blurred placeholder: the nearest shape that carries one
    var lq = null;
    for (var q = 0; q < fam.length; q++) if (fam[q].q && (!lq || Math.abs(Math.log(fam[q].a / a)) < Math.abs(Math.log(lq.a / a)))) lq = fam[q];
    return {{ p: best, url: P.dir + best.f + '?' + P.look, left: (W - w) / 2, top: top, w: w, h: h, lq: lq }};
  }};
  (function () {{
    try {{
      // signed in = the demo session, or (on the database, the default) this tab's Supabase session — unless this
      // load counts as having left صقر (window.SAKER_LEFT, set just above in index.html), which ends it
      var signedIn = false; try {{ signedIn = !!sessionStorage.getItem('saker.session') ||
        ((localStorage.getItem('saker.backend') || 'sb') === 'sb' && !window.SAKER_LEFT && !!sessionStorage.getItem('saker.auth')); }} catch (e) {{}}
      if (signedIn) return;
      var d = document.documentElement; d.classList.add('boot-signin');
      var W = d.clientWidth || innerWidth, H = d.clientHeight || innerHeight; if (!W || !H) return;
      var b = window.SAKER_POSTER_BOOT(W, H); if (!b) return;
      var s = d.style, px = function (v) {{ return v.toFixed(2) + 'px'; }};
      if (b.lq) {{ s.setProperty('--si-lqip', 'url(' + b.lq.q + ')'); s.setProperty('--si-lqip-y', (b.lq.h * 100).toFixed(1) + '%'); }}
      // absolute: a url() inside a CSS variable resolves against the STYLESHEET that uses it (assets/), not this page
      s.setProperty('--si-poster', 'url("' + new URL(b.url, location.href).href + '")');
      s.setProperty('--si-poster-x', px(b.left)); s.setProperty('--si-poster-y', px(b.top));
      s.setProperty('--si-poster-w', px(b.w)); s.setProperty('--si-poster-h', px(b.h));
      var l = document.createElement('link'); l.rel = 'preload'; l.as = 'image'; l.href = b.url;
      l.setAttribute('fetchpriority', 'high'); document.head.appendChild(l);
      var im = new Image(); im.onload = function () {{ performance.mark && performance.mark('saker:poster'); }}; im.src = b.url;   // same fetch; marks "sharp"
    }} catch (e) {{}}
  }})();
  </script>
  <!-- posters:end -->"""

pat = re.compile(r'<!-- posters:begin.*?<!-- posters:end -->', re.S)
if pat.search(html):
    html = pat.sub(lambda m: block, html)
else:   # first run: replace the old one-line boot script
    old = re.compile(r'  <!-- not signed in → the sign-in owns the screen.*?</script>', re.S)
    assert old.search(html), 'boot script not found'
    html = old.sub(lambda m: '  ' + block, html)
open(html_path, 'w', encoding='utf-8', newline='\n').write(html)
print('inlined', len(man['list']), 'posters, look', man['look'], '-', len(block), 'bytes')

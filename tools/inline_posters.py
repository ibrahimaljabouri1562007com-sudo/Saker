"""Inline brand/posters/manifest.json into index.html (between the posters:begin / posters:end markers).

The inlined script runs in <head>, before anything is drawn:
  - picks the poster for this screen's shape (same rule as terrain.js pickPoster),
  - sets --si-lqip (the tiny blurred placeholder, painted with the very first frame),
  - starts downloading the poster at high priority, in parallel with the stylesheets.
Run after _guide/make-posters.html:  python -I tools/inline_posters.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
man = json.load(open(os.path.join(ROOT, 'brand', 'posters', 'manifest.json'), encoding='utf-8'))
html_path = os.path.join(ROOT, 'index.html')
html = open(html_path, encoding='utf-8').read()

block = f"""<!-- posters:begin (generated by tools/inline_posters.py from brand/posters/manifest.json — do not edit) -->
  <script>
  window.SAKER_POSTERS = {json.dumps(man, separators=(',', ':'))};
  (function () {{
    try {{
      var signedIn = false; try {{ signedIn = !!sessionStorage.getItem('saker.session'); }} catch (e) {{}}
      if (signedIn) return;
      var d = document.documentElement; d.classList.add('boot-signin');
      var W = innerWidth, H = innerHeight; if (!W || !H) return;
      // same rule as terrain.js pickPoster: the widest poster not wider than the screen
      var a = W / H, P = window.SAKER_POSTERS, best = null, fam = [];
      for (var i = 0; i < P.list.length; i++) if ((P.list[i].a < 0.8) === (a < 0.8)) fam.push(P.list[i]);
      fam.sort(function (x, y) {{ return x.a - y.a; }}); best = fam[0] || null;
      for (var j = 0; j < fam.length; j++) if (fam[j].a <= a * 1.002) best = fam[j];
      if (!best) return;
      // the blurred placeholder: the nearest shape that carries one
      var lq = null;
      for (var k = 0; k < fam.length; k++) if (fam[k].q && (!lq || Math.abs(Math.log(fam[k].a / a)) < Math.abs(Math.log(lq.a / a)))) lq = fam[k];
      if (lq) {{ d.style.setProperty('--si-lqip', 'url(' + lq.q + ')'); d.style.setProperty('--si-lqip-y', (lq.h * 100).toFixed(1) + '%'); }}
      var l = document.createElement('link'); l.rel = 'preload'; l.as = 'image'; l.href = P.dir + best.f;
      l.setAttribute('fetchpriority', 'high'); document.head.appendChild(l);
    }} catch (e) {{}}
  }})();
  </script>
  <!-- posters:end -->"""

pat = re.compile(r'<!-- posters:begin.*?<!-- posters:end -->', re.S)
if pat.search(html):
    html = pat.sub(lambda m: block, html)
else:   # first run: replace the old one-line boot script
    old = re.compile(r'  <!-- not signed in → the sign-in owns the screen.*?</script>', re.S)
    assert old.search(html), 'boot script not found'
    html = old.sub(lambda m: '  ' + block, html)
open(html_path, 'w', encoding='utf-8', newline='\n').write(html)
print('inlined', len(man['list']), 'posters, look', man['look'], '-', len(block), 'bytes')
